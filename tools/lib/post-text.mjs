// 오늘 인스타·스레드·X 에 올릴 **글**을 짓는다.
//
// 왜 여기로 뺐는가: 이 원고가 두 군데에서 필요하다 — 터미널로 보는 쪽
// (build-post.mjs) 과 아침에 저절로 열리는 홍보 대장(build-promo-page.mjs).
// 두 벌을 두면 한쪽만 고친 날부터 **화면에 보이는 글과 붙여 넣는 글이 달라진다.**
// 순위를 읽는 자리가 tti.mjs 한 곳인 것과 같은 까닭이다.
//
// ⚠️ 말투는 여기 박혀 있지만 **띠 이름과 순위는 하나도 박혀 있지 않다.** 문장을
//    더할 때도 그 규칙을 지킬 것 — 한 군데라도 이름을 적어 넣으면 그날부터 거짓말이다.
//
// ⚠️ 근거가 없으면 그 줄을 통째로 뺀다. 오늘 충이 없는데 "충이라 꼴찌" 라고
//    쓰지 않게 하려는 것이다. 빈 줄이 틀린 줄보다 낫다.

const 지지한글 = {
  子: '쥐', 丑: '소', 寅: '호랑이', 卯: '토끼', 辰: '용', 巳: '뱀',
  午: '말', 未: '양', 申: '원숭이', 酉: '닭', 戌: '개', 亥: '돼지',
};

/**
 * X 가 세는 길이. 280 이 한도다.
 *
 * ⚠️ 한글은 한 자가 **둘**로 세어진다. 그래서 눈으로 세면 반드시 틀린다 —
 *    140자쯤에서 이미 꽉 찬다. 주소는 길이와 상관없이 23 으로 친다(t.co 로 줄어서다).
 *    twitter-text 의 기본 설정을 그대로 옮긴 것이다.
 */
export function xLen(text) {
  let n = 0;
  const 나머지 = text.replace(/https?:\/\/\S+/g, () => { n += 23; return ''; });
  for (const ch of 나머지) {
    const c = ch.codePointAt(0);
    const 한칸 = (c <= 0x10ff) || (c >= 0x2000 && c <= 0x200d)
      || (c >= 0x2010 && c <= 0x201f) || (c >= 0x2032 && c <= 0x2037);
    n += 한칸 ? 1 : 2;
  }
  return n;
}

/**
 * @param {{rows:{rank:number,name:string,why:string}[],month:string,day:string,ji:string}} r
 *        tti.mjs 의 fetchRanking() 이 돌려준 것 그대로
 * @returns {{인스타:string, x:string, 카드:string, 날짜:string, 으뜸:object, 꼴찌:object,
 *            길이:number, 뺀줄:number}}
 */
export function 오늘글(r) {
  const 오늘띠 = 지지한글[r.ji] || '';
  const 이름 = (why) => r.rows.filter((x) => x.why === why).map((x) => x.name.replace(/띠$/, ''));
  const 삼합 = [...이름('삼합'), 오늘띠].filter(Boolean);
  const 육합 = 이름('육합')[0];
  const 으뜸 = r.rows[0];
  const 꼴찌 = r.rows[11];

  // 근거가 있는 줄만 세운다.
  //
  // 이 차례가 곧 **버릴 차례**다. X 는 280 을 넘으면 아예 안 올라가므로 뒤에서부터
  // 떨어져 나간다. 그러니 덜 아까운 것을 뒤에 둘 것 — 1위가 왜 1위인지(삼합)는
  // 이 글의 알맹이고, 꼴찌와 2위는 없어도 글이 선다.
  const 까닭 = [];
  if (삼합.length >= 2 && 오늘띠) 까닭.push(`일진이 ${오늘띠}(${r.ji})라 ${삼합.join('·')}가 한 묶음(삼합)으로 올라갔어요.`);
  if (꼴찌.why) 까닭.push(`${꼴찌.name}는 오늘 일진과 ${꼴찌.why}이라 맨 아래예요.`);
  if (육합) 까닭.push(`${육합}띠는 일진과 짝을 이뤄(육합) 그 뒤를 잇습니다.`);

  // ⚠️ 이 줄은 마지막까지 남긴다. "뽑기가 아니다" 가 우리를 다른 운세 계정과
  //    가르는 한 문장이라, 이걸 버리면 남는 것은 아무 데나 있는 오늘의 운세다.
  const 계산 = '뽑기가 아니라 계산이라, 같은 날 다시 열어도 순위는 그대로예요.';

  const 몸통 = (n) => [`오늘 1위는 ${으뜸.name}입니다.`, '', ...까닭.slice(0, n), '', 계산];
  const 줄 = (a) => a.join('\n');

  const 태그 = ['#오늘의운세', '#띠별운세', '#사주', '#명리학', `#${으뜸.name}`, `#${꼴찌.name}`];
  const 인스타 = 줄([...몸통(까닭.length), '', '열두 띠 전부는 프로필 링크에 있습니다 ↑', '', 태그.join(' ')]);

  // ⚠️ 주소 끝에 날짜를 붙인다. X 는 미리보기 카드를 **주소별로** 캐시해서, 같은
  //    `/tti?ref=x` 를 날마다 올리면 처음 받아 간 그림이 며칠씩 따라온다. 2026-08-30 에
  //    올리려던 글에 닷새 전(08-25) 「1위는 돼지띠」 카드가 붙어 나왔다 — 본문은
  //    원숭이띠라고 말하고 있었다. 서버는 멀쩡했다(og 태그는 그날 것이 맞게 나온다).
  //    `d=MMDD` 는 X 에게 처음 보는 주소라 카드를 새로 받아 가고, 우리 쪽 유입 집계는
  //    `ref` 만 읽으므로 그대로다. 길이도 안 는다 — 주소는 몇 자든 23 으로 세어진다.
  const 날짜 = `${String(r.month).padStart(2, '0')}${String(r.day).padStart(2, '0')}`;

  const x글 = (n) => 줄([...몸통(n), '', '열두 띠 전부 ↓',
    `https://myan.riger7070.workers.dev/tti?ref=x&d=${날짜}`, '', '#오늘의운세 #사주']);

  // 들어갈 때까지 뒤에서 한 줄씩 뺀다.
  let 쓴줄 = 까닭.length;
  while (쓴줄 > 0 && xLen(x글(쓴줄)) > 280) 쓴줄 -= 1;
  const x = x글(쓴줄);

  return {
    인스타,
    x,
    // 스레드는 X 와 같은 글을 쓴다. 본문 링크가 눌리고 미리보기 카드도 뜬다 —
    // 다른 점은 길이 제한(500)이 넉넉하다는 것뿐이라, X 에 맞춰 줄인 글을
    // 그대로 올려도 손해가 없다.
    스레드: x,
    카드: `insta/tti-${날짜.slice(0, 2)}-${날짜.slice(2)}.png`,
    날짜,
    으뜸,
    꼴찌,
    길이: xLen(x),
    뺀줄: 까닭.length - 쓴줄,
  };
}
