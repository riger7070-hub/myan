// 오늘 인스타·X 에 올릴 글을 터미널에 뽑는다.
//
//   npm run post
//
// 아침에 저절로 열리는 홍보 대장(promo/promo-page.html)에도 같은 글이 실린다.
// 그래서 **글을 짓는 자리는 lib/post-text.mjs 한 벌뿐이다** — 두 벌이면 한쪽만
// 고친 날부터 화면에 보이는 글과 붙여 넣는 글이 달라진다.
//
// 왜 손으로 안 쓰는가: 띠 순위는 날마다 바뀐다. 손으로 쓰면 어제 1위가 그대로
// 남는데, 그림에는 오늘 1위가 박혀 있으므로 **그림과 글이 서로 다른 띠를 말한다.**
// 아무 오류도 안 나고, 올리고 나서야 보인다. 그래서 숫자는 서버에서 받아 넣는다.

import { fetchRanking } from './lib/tti.mjs';
import { 오늘글 } from './lib/post-text.mjs';

const r = await fetchRanking();
const p = 오늘글(r);

const 칸 = (제목, 글, 그림, 덧) => {
  console.log(`\n${'─'.repeat(64)}\n  ${제목}\n${'─'.repeat(64)}`);
  console.log(글);
  console.log('·'.repeat(64));
  console.log(`  그림  ${그림}`);
  if (덧) console.log(`  ${덧}`);
};

칸('인스타그램  (본문 링크는 눌리지 않는다 — 프로필 링크로 보낸다)', p.인스타, p.카드);

칸('X · 스레드  (본문 링크가 눌리고 미리보기 카드까지 뜬다)', p.x,
  `${p.카드} — ⚠️ 붙이지 말 것. 그림을 올리면 링크 미리보기 카드가 사라진다(둘 중 하나만 뜬다).`,
  `길이  ${p.길이}/280${p.뺀줄 ? ` · 들어가느라 까닭 ${p.뺀줄}줄을 뺐다(인스타 쪽엔 그대로 있다)` : ''}`);

if (p.길이 > 280) console.log('\n⚠️ 다 빼도 280 을 넘는다 — 손으로 줄여야 한다.');
console.log(`\n그림에 박힌 1위: ${p.으뜸.name} · 일진 ${r.ji}. 글과 같은지 눈으로 한 번 볼 것.\n`);
