// 오늘 인스타·X 에 올릴 글을 뽑는다.
//
//   node tools/build-post.mjs
//
// 왜 손으로 안 쓰는가: 띠 순위는 날마다 바뀐다. 손으로 쓰면 어제 1위가 그대로
// 남는데, 그림에는 오늘 1위가 박혀 있으므로 **그림과 글이 서로 다른 띠를 말한다.**
// 아무 오류도 안 나고, 올리고 나서야 보인다. 그래서 숫자는 서버에서 받아 넣는다.
//
// ⚠️ 말투는 여기 박혀 있지만 **띠 이름과 순위는 하나도 박혀 있지 않다.** 문장을
//    더할 때도 그 규칙을 지킬 것 — 한 군데라도 이름을 적어 넣으면 그날부터 거짓말이다.
//
// ⚠️ 근거가 없으면 그 줄을 통째로 뺀다. 오늘 충이 없는데 "충이라 꼴찌" 라고
//    쓰지 않게 하려는 것이다. 빈 줄이 틀린 줄보다 낫다.

import { fetchRanking } from './lib/tti.mjs';

const 지지한글 = {
  子: '쥐', 丑: '소', 寅: '호랑이', 卯: '토끼', 辰: '용', 巳: '뱀',
  午: '말', 未: '양', 申: '원숭이', 酉: '닭', 戌: '개', 亥: '돼지',
};

/**
 * X 가 세는 길이. 280 이 한도다.
 *
 * ⚠️ 한글은 한 자가 **둘**로 세어진다. 그래서 눈으로 세면 반드시 틀린다 —
 *    140자쯤에서 이미 꽉 찬다. 주소는 길이와 상관없이 23 으로 친다(t.co 로 줄어서다).
 *    twitter-text 의 기본 설정을 그대로 옮긴 것이다.
 */
function xLen(text) {
  let n = 0;
  const 나머지 = text.replace(/https?:\/\/\S+/g, () => { n += 23; return ''; });
  for (const ch of 나머지) {
    const c = ch.codePointAt(0);
    const 한칸 = (c <= 0x10ff) || (c >= 0x2000 && c <= 0x200d)
      || (c >= 0x2010 && c <= 0x201f) || (c >= 0x2032 && c <= 0x2037);
    n += 한칸 ? 1 : 2;
  }
  return n;
}

const r = await fetchRanking();
const 오늘띠 = 지지한글[r.ji] || '';
const 이름 = (why) => r.rows.filter((x) => x.why === why).map((x) => x.name.replace(/띠$/, ''));
const 삼합 = [...이름('삼합'), 오늘띠].filter(Boolean);
const 육합 = 이름('육합')[0];
const 으뜸 = r.rows[0];
const 꼴찌 = r.rows[11];

// 근거가 있는 줄만 세운다.
//
// 이 차례가 곧 **버릴 차례**다. X 는 280 을 넘으면 아예 안 올라가므로 뒤에서부터
// 떨어져 나간다. 그러니 덜 아까운 것을 뒤에 둘 것 — 1위가 왜 1위인지(삼합)는
// 이 글의 알맹이고, 꼴찌와 2위는 없어도 글이 선다.
const 까닭 = [];
if (삼합.length >= 2 && 오늘띠) 까닭.push(`일진이 ${오늘띠}(${r.ji})라 ${삼합.join('·')}가 한 묶음(삼합)으로 올라갔어요.`);
if (꼴찌.why) 까닭.push(`${꼴찌.name}는 오늘 일진과 ${꼴찌.why}이라 맨 아래예요.`);
if (육합) 까닭.push(`${육합}띠는 일진과 짝을 이뤄(육합) 그 뒤를 잇습니다.`);

// ⚠️ 이 줄은 마지막까지 남긴다. "뽑기가 아니다" 가 우리를 다른 운세 계정과
//    가르는 한 문장이라, 이걸 버리면 남는 것은 아무 데나 있는 오늘의 운세다.
const 계산 = '뽑기가 아니라 계산이라, 같은 날 다시 열어도 순위는 그대로예요.';

const 몸통 = (n) => [`오늘 1위는 ${으뜸.name}입니다.`, '', ...까닭.slice(0, n), '', 계산];
const 줄 = (a) => a.join('\n');

const 태그 = ['#오늘의운세', '#띠별운세', '#사주', '#명리학', `#${으뜸.name}`, `#${꼴찌.name}`];
const 인스타 = 줄([...몸통(까닭.length), '', '열두 띠 전부는 프로필 링크에 있습니다 ↑', '', 태그.join(' ')]);

const x글 = (n) => 줄([...몸통(n), '', '열두 띠 전부 ↓',
  'https://myan.riger7070.workers.dev/tti?ref=x', '', '#오늘의운세 #사주']);

// 들어갈 때까지 뒤에서 한 줄씩 뺀다.
let 쓴줄 = 까닭.length;
while (쓴줄 > 0 && xLen(x글(쓴줄)) > 280) 쓴줄 -= 1;
const x = x글(쓴줄);
const 뺀줄 = 까닭.length - 쓴줄;

const 칸 = (제목, 글, 그림, 덧) => {
  console.log(`\n${'─'.repeat(64)}\n  ${제목}\n${'─'.repeat(64)}`);
  console.log(글);
  console.log('·'.repeat(64));
  console.log(`  그림  ${그림}`);
  if (덧) console.log(`  ${덧}`);
};

const 카드 = `insta/tti-${String(r.month).padStart(2, '0')}-${String(r.day).padStart(2, '0')}.png`;
칸('인스타그램  (본문 링크는 눌리지 않는다 — 프로필 링크로 보낸다)', 인스타, 카드);

const n = xLen(x);
칸('X  (본문 링크가 눌리고 미리보기 카드까지 뜬다)', x,
  `${카드} — ⚠️ 붙이지 말 것. 그림을 올리면 링크 미리보기 카드가 사라진다(둘 중 하나만 뜬다).`,
  `길이  ${n}/280${뺀줄 ? ` · 들어가느라 까닭 ${뺀줄}줄을 뺐다(인스타 쪽엔 그대로 있다)` : ''}`);

if (n > 280) console.log('\n⚠️ 다 빼도 280 을 넘는다 — 손으로 줄여야 한다.');
console.log(`\n그림에 박힌 1위: ${으뜸.name} · 일진 ${r.ji}. 글과 같은지 눈으로 한 번 볼 것.\n`);
