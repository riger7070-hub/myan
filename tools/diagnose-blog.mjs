// 블로그 글에서 AI 티가 나는 자리를 세어 본다.
//
//   node tools/diagnose-blog.mjs
//
// humanize-korean 규칙집(quick-rules.md)의 항목 가운데 **기계로 셀 수 있는 것만**
// 센다. 나머지는 사람이 읽고 판단해야 한다.
//
// ⚠️ 이 도구는 고치지 않는다. 세기만 한다. 어디를 볼지 알려 주는 것까지가 몫이다.
//    규칙집이 "탐지 없는 구간을 건드리지 않는다"고 못박아 두었기 때문이다.

import { readFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'blog');
const 어디 = process.argv[2] || DIR;

// 표 줄과 해시태그 줄은 글이 아니다. 문장으로 세면 안 된다.
const 본문만 = (src) =>
  src.split('\n')
    .filter((l) => !/^\s{2,}\S/.test(l) && !l.trim().startsWith('#'))
    .join('\n');

// 문장 끝을 찾는다. 마침표·물음표로 끊는다.
const 문장들 = (t) =>
  t.replace(/\n+/g, ' ').split(/(?<=[.?!])\s+/).map((s) => s.trim()).filter((s) => s.length > 1);

// 세는 항목. [이름, 정규식, 임계, 규칙집 번호]
const 볼것 = [
  ['~에 대해',        /에 대(해|하여|한)/g,                  1, 'A-1'],
  ['~를 통해',        /를? 통(해|하여)/g,                    3, 'A-2'],
  ['~에 있어서',      /에 있어(서)?/g,                       1, 'A-3'],
  ['~라는 점에서',    /라는 점에서/g,                        3, 'A-4'],
  ['가지고 있다',     /가지고 있/g,                          1, 'A-7'],
  ['이중 피동',       /(되어지|지게 되)/g,                   1, 'A-8'],
  ['~에 의해',        /에 의(해|하여)/g,                     1, 'A-9'],
  ['~을 위해',        /을? 위(해|하여)/g,                    3, 'A-11'],
  ['결산 관용구',     /(결론적으로|따라서|이를 통해|그러므로|요약하면|정리하자면|정리하면)/g, 3, 'D-1'],
  ['의의 과장',       /(시사하는 바|주목할 만|매우 중요)/g,   1, 'D-2'],
  ['열거 도입',       /(크게 [가-힣] ?가지|다음과 같은|[가-힣] ?가지를? 말씀|[가-힣] ?가지로 나)/g, 1, 'D-3'],
  ['hype 어휘',       /(혁신적|획기적|압도적|파격적|폭발적|전례 없)/g, 3, 'D-4'],
  ['결말 공식',       /(할 때입니다|시점입니다|할 순간)/g,    1, 'D-6'],
  ['문두 접속사',     /(^|\n)\s*(또한|따라서|즉|나아가|아울러|게다가|더욱이)/g, 5, 'H-1'],
  ['메타 진입',       /(^|\n)\s*(이는 |이 점에서|이 관점에서|이 말은)/g, 3, 'H-3'],
  ['~것이다 체',      /(것이다|것입니다)/g,                  3, 'I-1'],
  ['~라는 점에 있다', /(주목할 점은|라는 점에 있)/g,          1, 'I-2'],
  ['~다는 것이다',    /(다는 것이|다는 뜻이)/g,              2, 'I-3'],
  ['추측 종결',       /(로 보인다|로 판단된|여겨진|인 듯하)/g, 2, 'G-1'],
  ['볼드',            /\*\*/g,                               1, 'J-1'],
  ['대시',            /—/g,                                  2, 'J-3'],
  ['연결어미 뒤 쉼표', /(고|며|지만|면서|아서|어서),/g,        6, 'C-11'],
  ['A 아니라 B 대구', /(이|가|것)? ?아니라 /g,                2, 'C-8'],
];

const 파일들 = readdirSync(어디).filter((f) => f.endsWith('.txt'));
let 총문제 = 0;

for (const f of 파일들) {
  const 원본 = readFileSync(join(어디, f), 'utf8');
  const t = 본문만(원본);
  const ss = 문장들(t);

  const 걸린것 = [];
  for (const [이름, re, 임계, id] of 볼것) {
    const n = (t.match(re) || []).length;
    if (n >= 임계) 걸린것.push(`${id} ${이름} ${n}회`);
  }

  // E-2: 같은 종결어미가 몇 번이나 잇따르는지. 가장 긴 줄을 잰다.
  const 끝 = ss.map((s) => {
    const m = /([가-힣]{1,3})[.?!]$/.exec(s);
    return m ? m[1] : '';
  });
  let 최장 = 1, 이어짐 = 1;
  for (let i = 1; i < 끝.length; i++) {
    if (끝[i] && 끝[i] === 끝[i - 1]) { 이어짐++; 최장 = Math.max(최장, 이어짐); }
    else 이어짐 = 1;
  }

  // E-1: 문장 길이가 고른지. 표준편차와 가장 긴 문장을 본다.
  const 길이 = ss.map((s) => s.length);
  const 평균 = 길이.reduce((a, b) => a + b, 0) / 길이.length;
  const 편차 = Math.sqrt(길이.reduce((a, b) => a + (b - 평균) ** 2, 0) / 길이.length);
  const 단문 = 길이.filter((n) => n <= 15).length;
  const 장문 = 길이.filter((n) => n >= 80).length;

  if (최장 >= 4) 걸린것.push(`E-2 같은 종결어미 ${최장}문장 연속`);
  // ⚠️ 편차만 보면 안 된다. 짧은 문장을 많이 쓰면 편차가 **내려간다.** 그런데
  //    그건 단조로운 게 아니라 오히려 사람이 쓰는 리듬이다. 처음에 편차 20 밑을
  //    싸잡아 걸었더니 단문 15개짜리 글이 걸렸다. 규칙집 E-1 이 말하는 것은
  //    "길이가 고르고 **긴 문장이 아예 없는**" 경우다. 둘 다일 때만 건다.
  const 단문비 = 단문 / 길이.length;
  if (편차 < 20 && 단문비 < 0.15 && 장문 === 0) {
    걸린것.push(`E-1 길이가 고르고 긴 문장이 없음 (편차 ${편차.toFixed(1)}, 단문 ${(단문비 * 100).toFixed(0)}%)`);
  }

  총문제 += 걸린것.length;
  console.log(`\n${f}`);
  console.log(`  문장 ${ss.length}개 · 평균 ${평균.toFixed(0)}자 · 편차 ${편차.toFixed(1)} · 단문 ${단문} · 장문 ${장문}`);
  if (걸린것.length) for (const g of 걸린것) console.log(`  ✖ ${g}`);
  else console.log('  깨끗하다');
}

console.log(`\n걸린 곳 ${총문제}군데`);
