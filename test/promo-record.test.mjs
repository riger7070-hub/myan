// 아침 홍보 대장이 **엉뚱한 곳에 엉뚱한 원고를 붙이지 않는지** 본다.
//
// 이 대장은 사람이 눈으로 검사하지 않는다 — 아침에 열려서 "오늘 여기 올리세요"
// 라고 말하면 그대로 올라간다. 그래서 틀리면 틀린 채로 나간다.
//
// ⚠️ 만들어진 promo-page.html 을 읽어서 재지 않는다. **자기가 만든 것을 자로
//    삼으면 무엇을 재도 맞는다** — 실제로 블로그 쪽에서 그렇게 당했다(링크 거는
//    코드를 통째로 지워도 검사가 통과했다). 여기서는 재료가 되는 두 파일
//    (promo/기록.md, docs/홍보.md)에서 기대값을 뽑는다.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { 기록읽기, 대목나누기, 대목찾기 } from '../tools/lib/promo-record.mjs';

const 기록원문 = readFileSync(new URL('../promo/기록.md', import.meta.url), 'utf8');
const 홍보원문 = readFileSync(new URL('../docs/홍보.md', import.meta.url), 'utf8');
const 기록 = 기록읽기(기록원문);
const 대목 = 대목나누기(홍보원문);

test('기록.md 의 모든 줄을 읽는다', () => {
  assert.deepEqual(기록.이상한줄, [],
    '모양이 어긋난 줄이 있다. 그 곳은 대장에 아예 안 나온다 — 조용히 사라진다');
});

test('올렸다고 표시한 줄에는 올린 날짜가 있다', () => {
  // "어제", "지난주" 는 며칠만 지나면 거짓말이 된다. 홍보.md 가 원고에 상대
  // 날짜를 쓰지 말라고 못 박은 것과 같은 까닭이다.
  for (const 것 of [...기록.한번, ...기록.날마다].filter((x) => x.올림)) {
    assert.match(것.날, /^\d{4}-\d{2}-\d{2}$/, `${것.이름} 의 올린 날짜가 없다`);
  }
});

test('세어 보면 기록.md 의 체크 줄 수와 같다', () => {
  // 읽는 규칙이 조용히 한 줄을 흘리면 여기서 걸린다.
  //
  // ⚠️ 파일 맨 위 설명에도 `- [ ] 이름 | 주소 | …` 두 줄이 **본보기로** 들어
  //    있다. 그건 올릴 곳이 아니다 — 첫 `## ` 아래부터 센다.
  const 몸 = 기록원문.slice(기록원문.search(/^## /m));
  const 날것 = 몸.split(/\r?\n/).filter((l) => /^\s*-\s*\[[ x]\]/.test(l)).length;
  assert.equal(기록.한번.length + 기록.날마다.length + 기록.이상한줄.length, 날것);
});

test('한 곳도 빠짐없이 주소를 갖는다', () => {
  for (const 것 of [...기록.한번, ...기록.날마다]) {
    assert.match(것.주소, /^https?:\/\//, `${것.이름} 의 주소가 이상하다`);
  }
});

test('올릴 곳이 남아 있으면 맨 위가 오늘 할 곳이다', () => {
  const 남은 = 기록.한번.filter((x) => !x.올림);
  // 다 비는 날이 오면 이 시험은 "다 돌았다" 를 확인하는 쪽으로 뜻이 바뀐다.
  if (남은.length) assert.equal(남은[0].올림, false);
});

// ── 원고를 엉뚱한 곳에 붙이지 않는가 ────────────────────────────────────────
//
// ⚠️ 이게 이 파일에서 제일 중요한 시험이다. 그냥 includes 로 훑으면 「긱뉴스」가
//    「디스콰이엇 · 긱뉴스」에 먼저 걸려서 **긱뉴스 자리에 디스콰이엇 원고가
//    붙는다.** 오류도 경고도 없고, 올릴 때가 되어서야 보인다.
test('긱뉴스에는 긱뉴스 원고가 붙는다', () => {
  const 찾음 = 대목찾기(대목, '긱뉴스');
  assert.ok(찾음, '긱뉴스 대목을 못 찾았다');
  assert.ok(찾음.제목.startsWith('긱뉴스'),
    `긱뉴스 자리에 「${찾음.제목}」 이 붙었다`);
});

test('디스콰이엇에는 디스콰이엇 원고가 붙는다', () => {
  const 찾음 = 대목찾기(대목, '디스콰이엇');
  assert.ok(찾음?.제목.startsWith('디스콰이엇'), '디스콰이엇 대목이 어긋났다');
});

test('대목마다 서로 다른 원고가 붙는다', () => {
  // 두 곳이 같은 대목을 가리키면 한 곳은 남의 원고를 올리게 된다.
  // (디스콰이엇 · 긱뉴스처럼 제목 하나에 둘이 묶인 경우는 홍보.md 가 그렇게
  //  쓴 것이니, 시작 글자로 갈리는지만 본다.)
  const 붙은것 = new Map();
  for (const 것 of 기록.한번) {
    const 찾음 = 대목찾기(대목, 것.이름);
    if (!찾음) continue;
    assert.ok(찾음.제목.startsWith(것.이름) || 찾음.제목.includes(것.이름),
      `${것.이름} 에 「${찾음.제목}」 이 붙었다`);
    붙은것.set(것.이름, 찾음.제목);
  }
  assert.ok(붙은것.size >= 4, '원고가 붙은 곳이 너무 적다 — 대목 이름이 바뀌었는지 볼 것');
});

test('홍보.md 의 마지막 대목도 읽힌다', () => {
  // ⚠️ 처음엔 정규식 하나로 잘랐는데 `\Z` 가 자바스크립트에 없어서 그냥 글자 Z 였다.
  //    오류가 안 나고 **마지막 대목만 조용히 사라졌다.** 그 자리를 지키는 시험이다.
  const 제목들 = [...홍보원문.matchAll(/^### (.+)$/gm)].map((m) => m[1].trim());
  assert.equal(대목.size, 제목들.length, '읽어 낸 대목 수가 홍보.md 의 `###` 수와 다르다');
  assert.ok(대목.get(제목들.at(-1))?.length > 0, '마지막 대목이 비었다');
});

// ── 같은 곳에 날마다 올리라고 시키지 않는가 ────────────────────────────────
test('한 번만 올리는 곳과 날마다 올리는 곳이 겹치지 않는다', () => {
  // 커뮤니티에 날마다 올리면 대부분 밴이다. 두 묶음에 같은 이름이 들어가면
  // 대장이 커뮤니티를 날마다 시키게 된다.
  const 한번이름 = new Set(기록.한번.map((x) => x.이름));
  for (const 것 of 기록.날마다) {
    assert.ok(!한번이름.has(것.이름),
      `${것.이름} 이 양쪽에 다 있다 — 커뮤니티를 날마다 올리라고 시키게 된다`);
  }
});

test('날마다 올리는 곳은 내 채널뿐이다', () => {
  const 내채널 = ['X', '인스타그램', '스레드', '네이버 블로그'];
  for (const 것 of 기록.날마다) {
    assert.ok(내채널.includes(것.이름),
      `${것.이름} 은 내 채널이 아니다. 날마다 올리면 규정에 걸린다`);
  }
});

test('올리지 말라고 적어 둔 곳이 목록에 없다', () => {
  const 금지 = ['디시', '뽐뿌', '클리앙', 'r/tarot', 'r/astrology'];
  for (const 것 of [...기록.한번, ...기록.날마다]) {
    for (const 나쁜곳 of 금지) {
      assert.ok(!것.이름.includes(나쁜곳), `${것.이름} 은 홍보 금지인 곳이다`);
    }
  }
});
